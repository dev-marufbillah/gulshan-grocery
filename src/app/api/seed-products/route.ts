export async function GET() {
  try {
    await connectDB();

    // 🌟 Upsert products (Add or update if exists by slug)
    for (const item of REAL_PRODUCTS) {
      await Product.findOneAndUpdate(
        { slug: item.slug },
        { ...item, emoji: "🛒" },
        { upsert: true, new: true }
      );
    }

    const totalCount = await Product.countDocuments({});

    return NextResponse.json({
      success: true,
      message: `${REAL_PRODUCTS.length} real products added/updated successfully!`,
      totalProductsInDatabase: totalCount,
    });
  } catch (err) {
    console.error("Seed Error:", err);
    return NextResponse.json(
      { error: "Failed to seed real products" },
      { status: 500 }
    );
  }
}